#!/usr/bin/env bash
# سامانه لجستیک حامی - اسکریپت اجرای سرور شبکه محلی برای لینوکس و مک

echo "======================================================================"
echo "         سامانه لجستیک و مدیریت ترابری حامی"
echo "          راه اندازی سرور محلی و اشتراک در شبکه LAN"
echo "======================================================================"

if ! command -v node &> /dev/null; then
    echo "[خطا] Node.js یافت نشد. لطفاً ابتدا Node.js را نصب کنید: https://nodejs.org"
    exit 1
fi

if [ ! -d "dist" ]; then
    echo "[*] در حال بیلد پروژه..."
    npm run build
fi

echo "[*] در حال اجرای سرور محلی..."
node lan-server.cjs
