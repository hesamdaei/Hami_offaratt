export function getInitialStaffAttendanceRecords(): AttendanceRecords {
  const records: AttendanceRecords = {};
  const currentYear = 1405;
  const currentMonth = 7; // مهر

  INITIAL_STAFF_MEMBERS.forEach((staff, idx) => {
    records[staff.id] = {};
    for (let day = 1; day <= 30; day++) {
      const dateKey = `${currentYear}/${currentMonth}/${day}`;
      // Realistic simulation: mostly present, some leave or mission
      if (day === 15) {
        // Today!
        if (idx === 4) {
          records[staff.id][dateKey] = 'workshop'; // استراحت / تعمیرگاه
        } else if (idx === 7) {
          records[staff.id][dateKey] = 'leave'; // مرخصی
        } else if (idx === 1 || idx === 3 || idx === 6) {
          records[staff.id][dateKey] = 'mission'; // در مأموریت
        } else {
          records[staff.id][dateKey] = 'none'; // حاضر
        }
      } else if (day % 7 === 6) {
        // جمعه‌ها
        records[staff.id][dateKey] = idx % 2 === 0 ? 'leave' : 'none';
      } else if ((idx + day) % 19 === 0) {
        records[staff.id][dateKey] = 'leave';
      } else if ((idx * 3 + day) % 23 === 0) {
        records[staff.id][dateKey] = 'mission';
      } else {
        records[staff.id][dateKey] = 'none';
      }
    }
  });

  // Merge exact decoded backup staff attendance records
  if (DECODED_BACKUP?.staffRecords) {
    Object.keys(DECODED_BACKUP.staffRecords).forEach((staffId) => {
      if (!records[staffId]) records[staffId] = {};
      Object.assign(records[staffId], DECODED_BACKUP.staffRecords[staffId]);
    });
  }

  return records;
}
